"""PDF and TXT text extraction.

Extraction is kept separate from cleaning and chunking. Uploaded bytes are
never written to disk or executed, and the original filename is only used as
display metadata (document IDs are generated by the ingestion service).
"""

from __future__ import annotations

import codecs
import logging
import re
from dataclasses import dataclass
from pathlib import PurePosixPath

from app.core.errors import (
    DocumentProcessingError,
    DocumentValidationError,
    ImageOnlyPdfError,
)

logger = logging.getLogger(__name__)

SUPPORTED_EXTENSIONS = {".pdf", ".txt"}
_PDF_CONTENT_TYPES = {
    "application/pdf",
    "application/x-pdf",
    "application/octet-stream",
    "",
}
_TXT_CONTENT_TYPES = {
    "text/plain",
    "application/octet-stream",
    "",
}
_CONTROL_CHAR = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


@dataclass(frozen=True, slots=True)
class ExtractedPage:
    page_number: int | None
    text: str


@dataclass(frozen=True, slots=True)
class ExtractedDocument:
    filename: str
    extension: str
    content_type: str | None
    pages: tuple[ExtractedPage, ...]
    page_count: int
    character_count: int
    encoding: str | None = None


def sanitize_filename(raw_name: str | None) -> str:
    """Return a safe display filename (no directory components or controls)."""
    if not raw_name:
        raise DocumentValidationError("A filename is required.")
    name = raw_name.replace("\\", "/").split("/")[-1]
    name = _CONTROL_CHAR.sub("", name).replace("\x00", "").strip()
    if name in {"", ".", ".."}:
        raise DocumentValidationError("The provided filename is invalid.")
    if len(name) > 200:
        stem = PurePosixPath(name).stem[:180]
        suffix = PurePosixPath(name).suffix[:19]
        name = f"{stem}{suffix}"
    return name


def validate_upload_metadata(
    raw_filename: str | None,
    content_type: str | None,
) -> tuple[str, str, str | None]:
    """Validate filename/content type and return (safe name, ext, media type)."""
    filename = sanitize_filename(raw_filename)
    extension = PurePosixPath(filename).suffix.lower()
    if extension not in SUPPORTED_EXTENSIONS:
        raise DocumentValidationError(
            f"Unsupported file type '{extension or 'unknown'}'. "
            "Only PDF (.pdf) and plain text (.txt) files are supported."
        )

    media_type = (content_type or "").split(";")[0].strip().lower()
    if extension == ".pdf":
        if media_type not in _PDF_CONTENT_TYPES:
            raise DocumentValidationError(
                f"Content type '{media_type}' is not valid for a PDF upload."
            )
    else:
        if media_type not in _TXT_CONTENT_TYPES and not media_type.startswith("text/"):
            raise DocumentValidationError(
                f"Content type '{media_type}' is not valid for a TXT upload."
            )
    return filename, extension, media_type or None


class DocumentProcessor:
    """Extracts ordered pages from PDF and TXT payloads."""

    def validate(self, filename: str | None, content_type: str | None) -> tuple[str, str, str | None]:
        return validate_upload_metadata(filename, content_type)

    def extract(
        self,
        data: bytes,
        filename: str | None,
        content_type: str | None,
    ) -> ExtractedDocument:
        safe_name, extension, media_type = validate_upload_metadata(filename, content_type)
        if not data:
            raise DocumentValidationError("The uploaded file is empty.")

        if extension == ".pdf":
            return self._extract_pdf(data, safe_name, media_type)
        return self._extract_txt(data, safe_name, media_type)

    # -- PDF ---------------------------------------------------------------

    def _extract_pdf(
        self,
        data: bytes,
        filename: str,
        content_type: str | None,
    ) -> ExtractedDocument:
        try:
            import pymupdf as fitz  # PyMuPDF >= 1.24 exposes the pymupdf name
        except ImportError:  # pragma: no cover - older PyMuPDF
            try:
                import fitz
            except ImportError as exc:
                raise DocumentProcessingError("PyMuPDF is not installed.") from exc

        try:
            document = fitz.open(stream=data, filetype="pdf")
        except Exception as exc:  # noqa: BLE001 - PyMuPDF raises several types
            logger.warning("Failed to open PDF %s: %s", filename, exc)
            raise DocumentProcessingError(
                "The PDF could not be opened. It may be corrupt or not a valid PDF."
            ) from exc

        try:
            if document.needs_pass or document.is_encrypted:
                raise DocumentProcessingError(
                    "Password-protected PDFs are not supported. "
                    "Please upload an unlocked PDF."
                )

            pages: list[ExtractedPage] = []
            for index in range(document.page_count):
                try:
                    page = document.load_page(index)
                    raw_text = page.get_text("text")
                except Exception as exc:  # noqa: BLE001
                    logger.warning("Failed to extract PDF page %s: %s", index + 1, exc)
                    raise DocumentProcessingError(
                        f"Text extraction failed on page {index + 1} of the PDF."
                    ) from exc
                if raw_text and raw_text.strip():
                    pages.append(ExtractedPage(page_number=index + 1, text=raw_text.strip()))

            total_alnum = sum(
                1 for page in pages for char in page.text if char.isalnum()
            )
            if not pages or total_alnum < 10:
                raise ImageOnlyPdfError(
                    "No extractable text was found in this PDF. It may contain "
                    "images/scans only. OCR is not implemented in this phase; "
                    "please upload a text-based PDF or a TXT file."
                )

            character_count = sum(len(page.text) for page in pages)
            return ExtractedDocument(
                filename=filename,
                extension=".pdf",
                content_type=content_type,
                pages=tuple(pages),
                page_count=document.page_count,
                character_count=character_count,
            )
        finally:
            document.close()

    # -- TXT ---------------------------------------------------------------

    def _extract_txt(
        self,
        data: bytes,
        filename: str,
        content_type: str | None,
    ) -> ExtractedDocument:
        text, encoding = decode_text_bytes(data)
        if not text.strip():
            raise DocumentValidationError("The TXT file contains no text.")

        page = ExtractedPage(page_number=None, text=text)
        return ExtractedDocument(
            filename=filename,
            extension=".txt",
            content_type=content_type,
            pages=(page,),
            page_count=1,
            character_count=len(text),
            encoding=encoding,
        )


def decode_text_bytes(data: bytes) -> tuple[str, str]:
    """Decode uploaded text bytes with common encodings.

    UTF BOMs and UTF-8 are handled first. For legacy encodings
    ``charset-normalizer`` is used, followed by a strict CP1252 attempt.
    Clearly binary payloads are rejected instead of being decoded silently.
    """
    if not data:
        raise DocumentValidationError("The uploaded file is empty.")

    if data.startswith(codecs.BOM_UTF8):
        return _decode_with(data, "utf-8-sig")
    if data.startswith((codecs.BOM_UTF32_LE, codecs.BOM_UTF32_BE)):
        return _decode_with(data, "utf-32")
    if data.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        return _decode_with(data, "utf-16")
    if b"\x00" in data[:4096]:
        raise DocumentValidationError(
            "The TXT file appears to be binary or uses an unsupported encoding."
        )

    try:
        return data.decode("utf-8"), "utf-8"
    except UnicodeDecodeError:
        pass

    detected: list[str] = []
    try:
        from charset_normalizer import from_bytes

        match = from_bytes(data).best()
        if match is not None and match.encoding:
            detected.append(match.encoding)
    except Exception as exc:  # noqa: BLE001 - CP1252 fallback still applies
        logger.debug("charset-normalizer failed for TXT upload: %s", exc)

    # Statistical detection is unreliable for very short payloads, where the
    # legacy Windows CP1252 encoding is the most common realistic case.
    if len(data) < 64 and detected and not detected[0].lower().startswith("utf"):
        candidates = ["cp1252", *detected]
    else:
        candidates = [*detected, "cp1252"]

    for encoding in candidates:
        text = _try_decoding(data, encoding)
        if text is not None:
            return text, encoding

    raise DocumentValidationError(
        "The TXT file could not be decoded. Please save it as UTF-8."
    )


def _try_decoding(data: bytes, encoding: str) -> str | None:
    """Decode with ``encoding``; return None if the result looks implausible."""
    try:
        text = data.decode(encoding)
    except (UnicodeDecodeError, LookupError):
        return None
    if not text.strip():
        return None
    controls = sum(1 for char in text if ord(char) < 32 and char not in "\n\r\t")
    if controls / max(len(text), 1) > 0.02:
        return None
    return text


def _decode_with(data: bytes, encoding: str) -> tuple[str, str]:
    try:
        text = data.decode(encoding)
    except UnicodeDecodeError as exc:
        raise DocumentValidationError(
            f"The TXT file could not be decoded as {encoding}."
        ) from exc
    _check_decoded_text(text, encoding)
    return text, encoding


def _check_decoded_text(text: str, encoding: str) -> None:
    if not text.strip():
        raise DocumentValidationError("The TXT file contains no text.")
    controls = sum(
        1 for char in text if ord(char) < 32 and char not in "\n\r\t"
    )
    if controls / max(len(text), 1) > 0.02:
        raise DocumentValidationError(
            "The TXT file appears to be binary or was decoded incorrectly. "
            "Please save it as UTF-8."
        )
